    public function __get(string $name): mixed
    {
        return $this->get($name);
    }

    public function __isset(string $name): bool
    {
        return $this->has($name);
    }

    public function tag(string $tag, string ...$abstracts): void
    {
        foreach ($abstracts as $abstract) {
            $this->tags[$tag][] = $abstract;
        }
    }

    public function tagged(string $tag): array
    {
        if (!isset($this->tags[$tag])) {
            return [];
        }
        $result = [];
        foreach ($this->tags[$tag] as $abstract) {
            $result[] = $this->make($abstract);
        }
        return $result;
    }

    /**
     * Register a contextual binding.
     *
     * $needed can be a parameter name OR an interface/class name.
     * Examples:
     *   contextual(Controller::class, LoggerInterface::class, FileLogger::class)
     *   contextual(Controller::class, 'diskPath', '/tmp/uploads')
     */
    public function contextual(string $needer, string $needed, string|callable $concrete): void
    {
        $this->contextualBindings[$needer][$needed] = $concrete;
    }

    /**
     * Invoke a callable (closure or [object, method]), auto-wiring its
     * parameters. Passes null as consumer since call() operates on
     * closures/methods, not class construction.
     */
    public function call(callable $callable, array $parameters = []): mixed
    {
        if (is_array($callable)) {
            [$object, $method] = $callable;

            // Cache the ReflectionMethod + its parameter list per Class::method.
            // The reflector is instance-independent, so invokeArgs() below can
            // reuse it for any instance — the controller-dispatch hot path then
            // skips ReflectionMethod construction entirely after the first hit.
            $key = (is_object($object) ? $object::class : $object) . '::' . $method;
            $meta = $this->callableCache[$key]
                ??= (static function () use ($object, $method): array {
                    $reflector = new \ReflectionMethod($object, $method);
                    return ['reflector' => $reflector, 'params' => $reflector->getParameters()];
                })();

            $dependencies = $this->resolveDependencies(null, $meta['params'], $parameters);

            return $meta['reflector']->invokeArgs($object, $dependencies);
        }

        $reflector = new \ReflectionFunction($callable);
        $dependencies = $this->resolveDependencies(null, $reflector->getParameters(), $parameters);

        return $reflector->invokeArgs($dependencies);
    }

    /** Register an alias that resolves to an existing binding */
    /**
     * Register a second name for an existing binding.
     *
     * The alias resolves through to the target every time rather than caching
     * anything of its own. Caching here silently promotes whatever it points at
     * to a singleton: alias(Guard::class, 'auth') over a scoped 'auth' handed
     * out the first request's guard for the life of the worker, still holding
     * that request's session. Visitor two was signed in as visitor one, or —
     * as it actually surfaced — signed in according to auth() and signed out
     * according to the middleware, because one read the alias and one read the
     * target.
     *
     * So: never a singleton, whatever the target is. The target's own binding
     * decides the lifetime, which is the only place that decision belongs.
     */
    /**
     * The name callbacks, extenders and instances are keyed under.
     *
     * An alias and its target must agree, or a hook registered against one
     * would never fire for the other.
     */
    protected function normalizeAbstract(string $abstract): string
    {
        return $this->aliasTargets[$abstract] ?? $abstract;
    }

    public function alias(string $alias, string $abstract): void
    {
        $this->aliasTargets[$alias] = $abstract;
        $this->services[$alias] = [
            'value'     => fn($container) => $container->get($abstract),
            'singleton' => false,
        ];
    }
}